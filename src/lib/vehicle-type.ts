/**
 * คำสะกด "ประเภทรถ" ให้เป็นแบบเดียวกันทั้งระบบ
 *
 * ระบบจับคู่งานกับเส้นทางด้วย ต้นทาง + ปลายทาง + ประเภทรถ โดยเทียบตัวอักษรตรงๆ
 * ถ้าทะเบียนรถเขียน "รถดั๊ม" แต่เส้นทางเขียน "รถดั๊มพ์" ระบบจะมองเป็นคนละประเภท
 * แล้วขึ้นเตือน «ไม่พบเส้นทาง» ทั้งที่ตั้งเส้นทางไว้แล้ว
 *
 * แก้ด้วยการยึดคำสะกดเดียว แล้วแปลงคำที่เคยใช้กันคนละแบบให้ตรงกันตั้งแต่ตอนนำเข้า
 * (ไม่ใช้วิธีให้ระบบเดาว่าสองคำนี้คือตัวเดียวกัน เพราะข้อมูลจะยังเพี้ยนอยู่
 *  ตารางจะมีสองแถวที่หน้าตาเหมือนกัน และคนใช้จะไม่รู้ว่าต้องตั้งราคาที่แถวไหน)
 */

/** คำที่เคยใช้ → คำมาตรฐานที่ระบบยึด */
export const VEHICLE_TYPE_ALIASES: Record<string, string> = {
  รถดั๊มพ์: "รถดั๊ม",
  รถดัมพ์: "รถดั๊ม",
  รถดั้ม: "รถดั๊ม",
  รถดัม: "รถดั๊ม",
  "รถดั๊มพ": "รถดั๊ม",
};

/** ตัดช่องว่างซ้ำ แล้วเปลี่ยนคำสะกดเก่าให้เป็นคำมาตรฐาน */
export function normalizeVehicleType(input: string): string {
  const s = input.trim().replace(/\s+/g, " ");
  return VEHICLE_TYPE_ALIASES[s] ?? s;
}

/**
 * คำที่ใช้แทน "ไม่มีหางพ่วง" ในช่องทะเบียนหาง
 *
 * รถเดี่ยว (เช่น รถดั๊ม รถหกล้อ) ไม่มีหาง แต่ในชีตช่องหางเป็น dropdown
 * ออฟฟิศเลยเลือกทะเบียนหลอกไว้ให้ผ่านๆ ไป กลายเป็นข้อมูลปลอมในระบบ
 * จึงให้มีตัวเลือก «รถเดี่ยว» ในชีต แล้วตอนนำเข้าเว็บแปลงเป็น "ไม่มีหาง" (null)
 */
export const NO_TRAILER = "รถเดี่ยว";

/** ค่าที่ถือว่า "ไม่มีหาง" — รวมคำที่ออฟฟิศมักพิมพ์เอง */
const NO_TRAILER_WORDS = new Set(["", "-", "—", NO_TRAILER, "ไม่มี", "ไม่มีหาง", "ไม่มีหางพ่วง", "รถเดี่ยว (ไม่มีหาง)"]);

/** ทะเบียนหางจากชีต/ฟอร์ม → ทะเบียนจริง หรือ null ถ้าเป็นรถเดี่ยว */
export function trailerOrNull(input: string | null | undefined): string | null {
  const s = (input ?? "").trim().replace(/\s+/g, " ");
  return NO_TRAILER_WORDS.has(s) ? null : s;
}
