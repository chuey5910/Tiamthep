/** สำหรับแสดงให้คนเลือก/อ่าน — เรียงตามตัวอักษรรหัสหมวด A B C H I J K L (STOCK_GROUPS เรียงตามลำดับการจับคำ ไม่ใช่ลำดับแสดง) */
export const STOCK_GROUPS_BY_LETTER = [...STOCK_GROUPS].sort((a, b) => a.letter.localeCompare(b.letter));

/** จัดหมวดจากชื่อสินค้า — คืนหมวด + คำที่ทำให้เข้าหมวดนี้ (ไว้บอกคน) · ไม่ตรงหมวดไหน = null (ห้ามเดา) */
export function groupOf(name: string): { group: StockGroup; because: string } | null {
  const n = name.replace(/\s+/g, "");
  for (const g of STOCK_GROUPS) {
    const s = g.starts.find((w) => n.startsWith(w));
    if (s) return { group: g, because: s };
    const c = g.contains.find((w) => n.includes(w));
    if (c) return { group: g, because: c };
  }
  return null;
}

/** หมวดของสินค้าที่มีอยู่แล้ว (จากชื่อหมวดในคลัง) */
export function groupByName(category: string | null | undefined): StockGroup | null {
  return STOCK_GROUPS.find((g) => g.name === category) ?? null;
}

/** เลขสูงสุดของรหัสแบบ ตัวอักษร + ตัวเลข (A0157) ในคลัง — รหัสใหม่รันต่อจากนี้ */
export function maxCodeNumber(codes: string[]): number {
  let max = 0;
  for (const c of codes) {
    const m = c.match(/^[A-Za-z](\d+)$/);
    if (m) max = Math.max(max, Number(m[1]));
  }
  return max;
}
