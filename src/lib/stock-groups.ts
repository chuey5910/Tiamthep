export const GENERAL_GROUP = STOCK_GROUPS[STOCK_GROUPS.length - 1];

/** จัดหมวดจากชื่อสินค้า — คืนหมวด + คำที่ทำให้เข้าหมวดนี้ (ไว้บอกคน) */
export function groupOf(name: string): { group: StockGroup; because: string | null } {
  const n = name.replace(/\s+/g, "");
  for (const g of STOCK_GROUPS) {
    const s = g.starts.find((w) => n.startsWith(w));
    if (s) return { group: g, because: s };
    const c = g.contains.find((w) => n.includes(w));
    if (c) return { group: g, because: c };
  }
  return { group: GENERAL_GROUP, because: null };
}

/** เลขสูงสุดของรหัสแบบ ตัวอักษร + ตัวเลข (A0157) ในคลัง — รหัสใหม่รันต่อจากนี้ */
export function maxCodeNumber(codes: string[]): number {
  let max = 0;
  for (const c of codes) {
    const m = c.match(/^[A-Za-z](\d+)$/);
    if (m) max = Math.max(max, Number(m[1]));
  }
  return max;
}
